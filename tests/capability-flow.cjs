const assert = require('node:assert/strict');
const fs = require('node:fs');
require('./remote-only.cjs');
const { isCapabilityLabel } = require('../src/lib/capability-label.ts');
const { ensureCapacityGraph } = require('../src/lib/capacity-graph.ts');
for (const label of ['University of Westminster', 'Harvard University', 'College of London', 'Université de Paris', '北京大学', 'Acme LLC', 'MBA', 'Email: test@example.com']) assert.equal(isCapabilityLabel(label), false, label);
for (const label of ['Spanish', 'English', 'Final Cut Pro', 'Marketing', 'University teaching', 'Financial analysis']) assert.equal(isCapabilityLabel(label), true, label);
const invalid = { elements: ['University of Westminster', 'Spanish', 'English'], evidence: ['Education'], services: [] };
const valid = { elements: ['Spanish', 'English'], evidence: ['Spanish and English'], services: [] };
const skillGraph = Object.fromEntries(['industries','roles','hardSkills','commercialSkills','tools','languages','education','geographicContext','crossCulturalExperience','domainExpertise','creativeAbilities','salesAbilities','operationalAbilities','certifications','strengths','interests'].map(k=>[k,[]]));
skillGraph.hardSkills = ['University of Westminster','Acme','Spanish','English'];
skillGraph.education = ['University of Westminster'];
const result = ensureCapacityGraph({skillGraph, combinations:[invalid,valid], context:{workMode:'global_remote'}, profile:{name:'Jane',roles:[{company:'Acme'}],education:['University of Westminster'],rawEvidence:[{text:'Spanish and English'}]}});
assert.deepEqual(result.combinations, [valid]);
assert.deepEqual(result.skillGraph.hardSkills, ['Spanish','English']);
assert.deepEqual(result.skillGraph.education, ['University of Westminster']);
assert.ok(result.capacityGraph.nodes.every(n=>!['Acme','University of Westminster'].includes(n.label)));
const report=fs.readFileSync('src/components/report.tsx','utf8');
assert.ok(report.includes('.slice(0, 3)'));
assert.equal((report.match(/href="\/agent\?setup=intent"/g)||[]).length,2);
assert.ok(!report.includes('deleteAnalysis'));
const controls=fs.readFileSync('src/components/agent-controls.tsx','utf8');
assert.ok(!controls.includes('>Pause</button>') && !controls.includes('>Revoke authorization</button>'));
const onboarding=fs.readFileSync('src/components/agent-onboarding.tsx','utf8');
assert.ok(onboarding.includes('!existingAnalysisId && <button'));
assert.ok(onboarding.includes('await startAgent();'));
assert.ok(onboarding.includes('onChooseCapabilities='));
assert.ok(!onboarding.includes('expandCustomIntent('));
console.log('PASS: entity filtering, saved evidence, clean combinations, graph selection, CV reuse, 3 opportunities and hidden controls.');
