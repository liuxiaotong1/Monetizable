import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const code = ts.transpileModule(await readFile(new URL('../src/lib/quest/guest-access.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { trialAllows, readTrialCards, readPredictionDraft, trialKey, draftKey } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null };
assert.equal(trialAllows([], 'first'), true);
assert.equal(trialAllows(['first'], 'second'), true);
assert.equal(trialAllows(['first', 'second'], 'third'), false);
assert.equal(trialAllows(['first', 'second'], 'second'), true, 'Finishing or reviewing an allowed card must not consume another trial slot');
storage.set(trialKey, JSON.stringify(['first', 'first', 'second', null]));
assert.deepEqual(readTrialCards(), ['first', 'second']);
storage.set(trialKey, 'bad json');
assert.deepEqual(readTrialCards(), []);
const draft = { direction: 'bearish', confidence: 'medium', reason: 'Watch the support level', date: '2026-10-11', at: new Date().toISOString() };
storage.set(draftKey, JSON.stringify(draft));
assert.deepEqual(readPredictionDraft(), draft);
storage.set(draftKey, JSON.stringify({ ...draft, at: new Date(Date.now() - 86400001).toISOString() }));
assert.equal(readPredictionDraft(), undefined, 'Expired draft must not silently become a current prediction');
storage.set(draftKey, JSON.stringify({ ...draft, direction: 'invalid' }));
assert.equal(readPredictionDraft(), undefined);
console.log('Guest trial limits and draft recovery checks passed.');
