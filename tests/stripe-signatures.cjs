const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const crypto = require('node:crypto');
const path = require('node:path');
const filename = path.resolve(__dirname, '../src/lib/stripe.ts');
const mod = new Module(filename);
mod.filename = filename;
mod.paths = module.paths;
mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename);
const verify = mod.exports.verifyStripeSignature;
process.env.STRIPE_WEBHOOK_SECRET = 'whsec_regression_only';
const payload = '{"type":"invoice.paid"}';
const timestamp = Math.floor(Date.now() / 1000);
const sign = (t, secret = process.env.STRIPE_WEBHOOK_SECRET) => crypto.createHmac('sha256', secret).update(`${t}.${payload}`).digest('hex');
const valid = sign(timestamp), other = '0'.repeat(64);
assert.equal(verify(payload, `t=${timestamp},v1=${valid}`), true);
assert.equal(verify(payload, `t=${timestamp},v1=${valid},v1=${other}`), true);
assert.equal(verify(payload, `t=${timestamp},v1=${other},v1=${valid}`), true);
assert.equal(verify(payload, `t=${timestamp}, v1=${valid}`), true);
assert.equal(verify(payload + ' ', `t=${timestamp},v1=${valid}`), false);
assert.equal(verify(payload, `t=${timestamp},v1=${sign(timestamp, 'whsec_wrong')}`), false);
for (const t of [timestamp - 301, timestamp + 301, 'NaN', 'Infinity', '']) assert.equal(verify(payload, `t=${t},v1=${sign(t)}`), false);
for (const signature of ['', 'ff', 'z'.repeat(64)]) assert.equal(verify(payload, `t=${timestamp},v1=${signature}`), false);
assert.equal(verify(payload, `t=${timestamp},v0=${valid}`), false);
process.env.STRIPE_WEBHOOK_SECRET = '  whsec_regression_only\n';
assert.equal(verify(payload, `t=${timestamp},v1=${valid}`), true);
delete process.env.STRIPE_WEBHOOK_SECRET;
assert.equal(verify(payload, `t=${timestamp},v1=${valid}`), false);
console.log('PASS: Stripe signatures, rotation, tampering, secret mismatch and timestamp validation');
