const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const React = require('react');
function load(file, stubs = {}) {
  const mod = { exports: {} };
  const source = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
  new Function('require', 'module', 'exports', source)(name => stubs[name] ?? require(name), mod, mod.exports);
  return mod.exports;
}
const { locales, isLocale, localeForRequest, getMessages } = load('src/lib/i18n.ts');
assert.deepEqual(locales, ['en', 'fr']);
for (const locale of ['de', 'es', 'it', 'zh', '', 'FR', undefined]) assert.equal(isLocale(locale), false);
for (const country of ['FR', 'fr', 'MC', 'SN', 'RE']) assert.equal(localeForRequest(country, 'en-US'), 'fr');
for (const country of [null, '', 'XX', 'DE', 'CN', 'US']) assert.equal(localeForRequest(country, 'fr-FR'), 'en');
assert.equal(localeForRequest('CA', 'en;q=0.5,fr;q=1'), 'fr');
assert.equal(localeForRequest('CA', 'fr;q=0,en;q=1'), 'en');
assert.equal(localeForRequest('CH', 'de,fr;q=0.8'), 'en');
assert.equal(localeForRequest('BE', 'fr-BE,en;q=0.8'), 'fr');
assert.deepEqual(Object.keys(getMessages('en')).sort(), Object.keys(getMessages('fr')).sort());
const { translateText } = load('src/lib/localized-text.ts', { '@/lib/messages-fr.json': { 'Save': 'Enregistrer', 'For {0} days': 'Pendant {0} jours' } });
assert.equal(translateText(' Save ', 'fr'), ' Enregistrer ');
assert.equal(translateText('Save', 'en'), 'Save');
assert.equal(translateText('For 14 days', 'fr'), 'Pendant 14 jours');
assert.equal(translateText('Research × Marketing', 'fr', { Research: 'Recherche' }), 'Recherche × Marketing');
const { localizeTree } = load('src/components/localized.tsx', { '@/lib/localized-text': { translateText }, '@/components/localization-provider': {} });
const onChange = () => {};
const input = React.createElement('input', { value: 'Save', placeholder: 'Save', onChange });
const localizedInput = localizeTree(input, 'fr');
assert.equal(localizedInput.props.value, 'Save');
assert.equal(localizedInput.props.onChange, onChange);
assert.equal(localizedInput.props.placeholder, 'Enregistrer');
const option = localizeTree(React.createElement('option', null, 'Save'), 'fr');
assert.equal(option.props.value, 'Save');
assert.equal(option.props.children, 'Enregistrer');
const draft = React.createElement('textarea', { value: 'Save' });
assert.equal(localizeTree(draft, 'fr'), draft);
const source = React.createElement('span', { translate: 'no' }, 'Save');
assert.equal(localizeTree(source, 'fr'), source);
const link = localizeTree(React.createElement('a', { href: '/Save', 'data-id': 'Save' }, 'Save'), 'fr');
assert.equal(link.props.href, '/Save');
assert.equal(link.props['data-id'], 'Save');
assert.equal(link.props.children, 'Enregistrer');
console.log('PASS: locales, geography, quality weights, dictionary parity, display translation, stable form values, handlers, source data and URLs.');
