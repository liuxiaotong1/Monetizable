import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source=await fs.readFile('src/lib/quest/event-presentation.ts','utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {eventTakeaway,compactEventUnit}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const base={kind:'CPI',status:'confirmed',actual:3.7,previous:3.4,consensus:3.6};
assert.equal(compactEventUnit('% 同比，未季调'),'%');
assert.equal(compactEventUnit('千人，月度净新增非农就业'),'千人');
assert.equal(eventTakeaway(base,'zh').arrow,'↑');
assert.equal(eventTakeaway(base,'zh').tone,'pressure');
assert.match(eventTakeaway(base,'zh').title,/高于市场共识/);
assert.equal(eventTakeaway({...base,actual:3.3},'en').tone,'support');
assert.equal(eventTakeaway({...base,status:'pending'},'zh'),null);
assert.equal(eventTakeaway({...base,actual:undefined},'en'),null);
assert.equal(eventTakeaway({...base,consensus:undefined,previous:undefined,calendarValues:{forecast:3.6}},'en').tone,'mixed');
assert.match(eventTakeaway({...base,consensus:undefined},'zh').detail,/仅比较前值/);
assert.equal(eventTakeaway({...base,consensus:undefined,revised:3.8},'en').arrow,'↓');
assert.match(eventTakeaway({...base,kind:'CLAIMS',actual:200,consensus:220},'en').title,/Labor stronger/);
assert.match(eventTakeaway({...base,kind:'CLAIMS',actual:240,consensus:220},'zh').title,/就业降温/);
assert.equal(eventTakeaway({...base,kind:'GDP'},'en').tone,'mixed');
assert.equal(eventTakeaway({...base,kind:'TRADE'},'en').tone,'mixed');
assert.equal(eventTakeaway({...base,actual:3.6},'en').arrow,'↔');
assert.equal(eventTakeaway({...base,actual:NaN},'en'),null);
console.log('Event presentation comparisons, missing data, revisions and interpretation tests passed.');
